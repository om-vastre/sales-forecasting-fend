@app.route("/products", methods=["POST"])
def create_product():
    """
    Creates a new product.
    Expects JSON payload:
      {
        "ProductID": "<product_id>",
        "Price": <float>,
        "Discount": <float>,
        "QtyRemaining": <integer>,
        "access_token": "<user_access_token>"
      }
    """
    if not request.is_json:
        return jsonify({"error": "Request must be JSON."}), 400
    
    data = request.get_json()
    if not data:
        return jsonify({"error": "Request must contain JSON data."}), 400

    access_token = data.get("access_token")
    if not is_valid_access_token(access_token):
        return jsonify({"error": "Invalid access token."}), 401

    product_id = data.get("ProductID")
    price = data.get("Price")
    discount = data.get("Discount")
    qty_remaining = data.get("QtyRemaining")

    if not all([product_id, isinstance(product_id, str),
                price is not None, isinstance(price, (int, float)),
                discount is not None, isinstance(discount, (int, float)),
                qty_remaining is not None, isinstance(qty_remaining, int)]):
        return jsonify({"error": "Missing or invalid type for required fields: ProductID (string), Price (number), Discount (number), QtyRemaining (integer)."}), 400

    conn = None
    try:
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        cursor.execute(
            "INSERT INTO products (ProductID, Price, Discount, QtyRemaining) VALUES (?, ?, ?, ?)",
            (product_id, float(price), float(discount), int(qty_remaining))
        )
        conn.commit()
        app.logger.info(f"Product {product_id} created successfully.")
        return jsonify({"message": "Product created successfully.", "ProductID": product_id}), 201
    except sqlite3.IntegrityError:
        app.logger.error(f"Error creating product {product_id}: ProductID already exists.")
        return jsonify({"error": f"Product with ProductID '{product_id}' already exists."}), 409
    except sqlite3.Error as e:
        app.logger.error(f"Database error creating product: {str(e)}")
        return jsonify({"error": f"Database error: {str(e)}"}), 500
    except Exception as e:
        app.logger.error(f"Error creating product: {str(e)}")
        return jsonify({"error": "An internal server error occurred."}), 500
    finally:
        if conn:
            conn.close()

