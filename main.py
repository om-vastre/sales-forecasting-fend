@app.route("/getstats", methods=["POST"])
def get_stats():
    """
    Expects JSON payload:
      {
        "range": "This Day" | "Last 7 Days" | "Last 30 Days",
        "access_token": "<user_access_token>"
      }
    Retrieves sum of 'Units Sold' and 'Sales' for the specified period
    from the dataset.csv file.
    """
    try:
        # Validate access token
        access_token = request.json.get("access_token")
        if not is_valid_access_token(access_token):
            return jsonify({"error": "Invalid access token."}), 401

        if not request.is_json:
            return jsonify({"error": "Request must be JSON."}), 400
        
        payload = request.get_json()
        if not isinstance(payload, dict):
             return jsonify({"error": "Payload must be a JSON object."}), 400

        range_str = payload.get("range")

        if not range_str:
            return jsonify({"error": "'range' is required."}), 400

        if range_str == "This Day":
            x_days = 1
        elif range_str == "Last 7 Days":
            x_days = 7
        elif range_str == "Last 30 Days":
            x_days = 30
        else:
            return jsonify({"error": "Invalid range. Must be 'This Day', 'Last 7 Days', or 'Last 30 Days'."}), 400

        df = pd.read_csv(CSV_PATH)
        df["Date"] = pd.to_datetime(df["Date"])
        
        if df.empty:
            return jsonify({"rupees": 0, "qty": 0, "message": "Dataset is empty."}), 200

        max_date = df["Date"].max()
        start_date = max_date - pd.Timedelta(days=x_days - 1)
        
        filtered_df = df[(df["Date"] >= start_date) & (df["Date"] <= max_date)]

        total_sales_rupees = filtered_df["Sales"].sum()
        total_units_qty = filtered_df["Units Sold"].sum()

        return jsonify({"rupees": float(total_sales_rupees), "qty": int(total_units_qty)}), 200

    except Exception as e:
        app.logger.error(f"Getstats endpoint error: {str(e)}")
        return jsonify({"error": "An internal server error occurred."}), 500



