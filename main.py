# Endpoint: Predict on the last N days from CSV
# ------------------------------------------------------------------------
@app.route("/predict_last", methods=["POST"])
def predict_last():
    """
    Expects JSON payload:
      {
        "model": "week" or "month",
        "n_days": <integer>,
        "access_token": <string>
      }
    Reads the CSV, preprocesses it, builds X,y for the chosen target horizon,
    then takes the last n_days rows of X, predicts using the corresponding model,
    and returns a JSON mapping Date → Predicted_Sales for those last n_days.
    """
    # Validate access token
    access_token = request.json.get("access_token")
    if not is_valid_access_token(access_token):
        return jsonify({"error": "Invalid access token."}), 401
    if not request.is_json:
        return jsonify({"error": "Request must be JSON."}), 400
    if not request.json:
        return jsonify({"error": "Request must contain JSON data."}), 400
    if "model" not in request.json or "n_days" not in request.json:
        return jsonify({"error": "Request must contain 'model' and 'n_days' fields."}), 400
    
    try:
        payload = request.get_json()
        if not isinstance(payload, dict):
            raise ValueError("Payload must be a JSON object.")
        
        model_type = payload.get("model", "").lower()
        n_days = payload.get("n_days", None)
        
        if model_type not in ("week", "month"):
            raise ValueError("Field 'model' must be 'week' or 'month'.")
        if not isinstance(n_days, int) or n_days <= 0:
            raise ValueError("Field 'n_days' must be a positive integer.")
        
        # 1. Load CSV
        df_raw = pd.read_csv(CSV_PATH)
        
        # 2. Preprocess
        processed_df, _ = preprocess_data(df_raw)
        
        # 3. Prepare data for the chosen horizon
        if model_type == "week":
            target_days = 7
            model = model_week
        else:  # "month"
            target_days = 30
            model = model_month
        
        X_all, y_all, dates_all, feature_cols = prepare_model_data(processed_df, target_days)
        
        total_rows = X_all.shape[0]
        if n_days > total_rows:
            raise ValueError(f"Requested n_days ({n_days}) exceeds available rows ({total_rows}).")
        
        # 4. Select last n_days of X_all
        X_recent = X_all.iloc[-n_days:].reset_index(drop=True)
        dates_recent = dates_all.iloc[-n_days:].dt.strftime("%Y-%m-%d").tolist()
        
        # 5. Predict
        preds = model.predict(X_recent)
        
        # 6. Build response mapping each date to its predicted sales
        result = [
            {"Date": dates_recent[i], "Predicted_Sales": float(preds[i])}
            for i in range(n_days)
        ]
        
        return jsonify({"predictions": result}), 200
    
    except Exception as e:
        return jsonify({"error": str(e)}), 400


