@app.route("/login", methods=["POST"])
def login():
    """
    Expects JSON payload:
      {
        "email": "<user_email>",
        "pass": "<user_password>"
      }
    Checks credentials against the SQLite database.
    If correct, generates a 16-character access token, stores it globally,
    and returns it. Otherwise, returns an error.
    """
    try:
        payload = request.get_json()
        if not isinstance(payload, dict):
            return jsonify({"error": "Payload must be a JSON object."}), 400

        email = payload.get("email")
        password = payload.get("pass") # Using "pass" as per request

        if not email or not password:
            return jsonify({"error": "Email and password are required."}), 400

        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        # IMPORTANT: In a real app, passwords must be hashed and compared securely.
        # This example uses plaintext for simplicity as per the request's implication.
        cursor.execute("SELECT password FROM users WHERE email = ?", (email,))
        user_record = cursor.fetchone()
        conn.close()

        if user_record and user_record[0] == password:
            token = secrets.token_hex(8)  # Generates a 16-character hex token
            access_tokens.append(token)
            app.logger.info(f"Login successful for {email}, token generated.")
            return jsonify({"access_token": token}), 200
        else:
            app.logger.warning(f"Failed login attempt for {email}.")
            return jsonify({"error": "Invalid email or password."}), 401

    except Exception as e:
        app.logger.error(f"Login endpoint error: {str(e)}")
        return jsonify({"error": "An internal server error occurred."}), 500


