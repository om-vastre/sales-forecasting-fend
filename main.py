    values = list(fields_to_update.values())
    values.append(product_id)

    conn = None
    try:
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        cursor.execute(f"UPDATE products SET {set_clause} WHERE ProductID = ?", tuple(values))
        
        if cursor.rowcount == 0:
            app.logger.warning(f"Attempted to update product {product_id}, but it was not found or no changes were applicable.")
            return jsonify({"error": "Product not found or no changes made."}), 404
        
        conn.commit()
        app.logger.info(f"Product {product_id} updated successfully.")
        return jsonify({"message": f"Product {product_id} updated successfully."}), 200
    except sqlite3.Error as e:
        app.logger.error(f"Database error updating product {product_id}: {str(e)}")
        return jsonify({"error": f"Database error: {str(e)}"}), 500
    except Exception as e:
        app.logger.error(f"Error updating product {product_id}: {str(e)}")
