def preprocess_data(df: pd.DataFrame):
    """
    1. Convert 'Date' to datetime, sort by ['Product ID', 'Date'].
    2. Extract date components: Year, Month, Day, DayOfWeek, Quarter, WeekOfYear.
    3. For each 'Product ID', create lag features of 'Sales' at lags [1,7,14,30].
    4. Compute rolling mean/std of 'Sales' over windows [7,14,30] days per product.
    5. Derive price‐related features:
         - Price_vs_Competitor = Price / Competitor Pricing
         - Discount_Price_Ratio = Discount / Price
         - Effective_Price = Price * (1 - Discount / 100)
    6. Label‐encode categorical columns: 'Product ID', 'Category', 'Region',
       'Weather Condition', 'Seasonality'.
    Returns:
      - processed_df: DataFrame with new features (NaN rows from lags/rolls dropped).
      - encoders: dict mapping column name → fitted LabelEncoder.
    """
    df_proc = df.copy()
    # 1. Convert and sort
    df_proc["Date"] = pd.to_datetime(df_proc["Date"])
    df_proc = df_proc.sort_values(["Product ID", "Date"]).reset_index(drop=True)
    
    # 2. Date components
    df_proc["Year"] = df_proc["Date"].dt.year
    df_proc["Month"] = df_proc["Date"].dt.month
    df_proc["Day"] = df_proc["Date"].dt.day
    df_proc["DayOfWeek"] = df_proc["Date"].dt.dayofweek      # Monday=0 … Sunday=6
    df_proc["Quarter"] = df_proc["Date"].dt.quarter
    df_proc["WeekOfYear"] = df_proc["Date"].dt.isocalendar().week
    
    # 3. Lag features per product
    lag_days = [1, 7, 14, 30]
    for lag in lag_days:
        df_proc[f"Sales_lag_{lag}"] = df_proc.groupby("Product ID")["Sales"].shift(lag)
    
    # 4. Rolling mean & std per product for windows [7,14,30]
    roll_windows = [7, 14, 30]
    for window in roll_windows:
        df_proc[f"Sales_roll_mean_{window}"] = (
            df_proc.groupby("Product ID")["Sales"]
                   .rolling(window, min_periods=1)
                   .mean()
                   .shift(1)
                   .reset_index(level=0, drop=True)
        )
        df_proc[f"Sales_roll_std_{window}"] = (
            df_proc.groupby("Product ID")["Sales"]
                   .rolling(window, min_periods=1)
                   .std()
                   .shift(1)
                   .reset_index(level=0, drop=True)
        )
    
    # 5. Price-related features
    df_proc["Price_vs_Competitor"] = df_proc["Price"] / (df_proc["Competitor Pricing"] + 1e-6)
    df_proc["Discount_Price_Ratio"] = df_proc["Discount"] / (df_proc["Price"] + 1e-6)
    df_proc["Effective_Price"] = df_proc["Price"] * (1 - df_proc["Discount"] / 100)
    
    # 6. Label-encode categorical columns
    categorical_cols = ["Product ID", "Category", "Region", "Weather Condition", "Seasonality"]
    encoders = {}
    for col in categorical_cols:
        le = LabelEncoder()
        df_proc[f"{col}_encoded"] = le.fit_transform(df_proc[col].astype(str))
        encoders[col] = le
    
    # Drop any rows with NaNs generated by lags/rolling
    df_proc = df_proc.dropna().reset_index(drop=True)
    
    return df_proc, encoders

def create_forecasting_features(data: pd.DataFrame, target_days: int):
    """
    Shifts 'Sales' by -target_days within each 'Product ID' group to create the target variable.
    Returns a new DataFrame with a column 'Sales_target_{target_days}d'.
    """
    df_f = data.copy().sort_values(["Product ID", "Date"]).reset_index(drop=True)
    df_f[f"Sales_target_{target_days}d"] = (
        df_f.groupby("Product ID")["Sales"].shift(-target_days)
    )
    # Drop rows where target is NaN (last target_days per product)
    df_f = df_f.dropna(subset=[f"Sales_target_{target_days}d"]).reset_index(drop=True)
    return df_f

def prepare_model_data(data: pd.DataFrame, target_days: int):
    """
    1. Calls create_forecasting_features to get target column.
    2. Defines feature columns (the same as during training).
    3. Drops rows with any NaNs in those feature columns or the target.
    Returns:
      - X: DataFrame of features
      - y: Series of target (Sales_target_{target_days}d)
      - dates: Series of Date (for mapping predictions to dates)
      - feature_cols: list of feature names
    """
    df_feat = create_forecasting_features(data, target_days)
    
    feature_cols = [
        # Date components
        "Year", "Month", "Day", "DayOfWeek", "Quarter", "WeekOfYear",
        # Business features
        "Units Sold", "Price", "Discount", "Holiday/Promotion", "Competitor Pricing",
        # Encoded categoricals
        "Product ID_encoded", "Category_encoded", "Region_encoded",
        "Weather Condition_encoded", "Seasonality_encoded",
        # Lag features
        "Sales_lag_1", "Sales_lag_7", "Sales_lag_14", "Sales_lag_30",
        # Rolling statistics
        "Sales_roll_mean_7", "Sales_roll_std_7",
        "Sales_roll_mean_14", "Sales_roll_std_14",
        "Sales_roll_mean_30", "Sales_roll_std_30",
        # Price-ratio features
        "Price_vs_Competitor", "Discount_Price_Ratio", "Effective_Price"
    ]
    
    df_model = df_feat.dropna(subset=feature_cols + [f"Sales_target_{target_days}d"]).reset_index(drop=True)
    X = df_model[feature_cols].copy()
    y = df_model[f"Sales_target_{target_days}d"].copy()
    dates = df_model["Date"].copy()
    
    return X, y, dates, feature_cols

