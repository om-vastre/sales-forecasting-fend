@app.route("/download_dataset", methods=["GET"])
def download_dataset():
    """
    Allows authenticated users to download the dataset.csv file.
    Expects access_token as a query parameter: /download_dataset?access_token=<token>
    """
    access_token = request.args.get("access_token")
    if not is_valid_access_token(access_token):
        return jsonify({"error": "Invalid or missing access token."}), 401

    try:
        app.logger.info(f"Dataset download request received with valid token.")
        return send_file(
            CSV_PATH,
            mimetype='text/csv',
            as_attachment=True,
            download_name='records.csv' # This is the name the browser will suggest for the download
        )
    except FileNotFoundError:
        app.logger.error(f"Error downloading dataset: {CSV_PATH} not found.")
        return jsonify({"error": "Dataset file not found on server."}), 404
    except Exception as e:
        app.logger.error(f"Error during dataset download: {str(e)}")
        return jsonify({"error": "An internal server error occurred during file download."}), 500

