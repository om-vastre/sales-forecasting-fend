    if not is_valid_access_token(access_token):
        return jsonify({"error": "Invalid access token."}), 401

    fields_to_update = {}
    if "Price" in data:
        if not isinstance(data["Price"], (int, float)): return jsonify({"error": "Price must be a number."}), 400
        fields_to_update["Price"] = float(data["Price"])
    if "Discount" in data:
        if not isinstance(data["Discount"], (int, float)): return jsonify({"error": "Discount must be a number."}), 400
