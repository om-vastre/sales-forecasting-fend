@app.route("/add_entry", methods=["POST"])
def add_entry():
    """
    Adds a new entry to the dataset.csv file.
    Expects JSON payload with all required columns for the CSV and an access_token:
      {
        "Date": "YYYY-MM-DD",
        "Product ID": "string",
        "Category": "string",
        "Region": "string",
        "Units Sold": "integer",
        "Price": "float",
        "Discount": "float",
        "Weather Condition": "string",
        "Holiday/Promotion": "integer (0 or 1)",
        "Competitor Pricing": "float",
        "Seasonality": "string",
        "Sales": "float",
        "access_token": "<user_access_token>"
      }
    """
    if not request.is_json:
        return jsonify({"error": "Request must be JSON."}), 400
    
    data = request.get_json()
    if not data:
        return jsonify({"error": "Request must contain JSON data."}), 400

    access_token = data.get("access_token")
    if not is_valid_access_token(access_token):
        return jsonify({"error": "Invalid access token."}), 401

    required_fields = [
        "Date", "Product ID", "Category", "Region", "Units Sold", "Price",
        "Discount", "Weather Condition", "Holiday/Promotion",
        "Competitor Pricing", "Seasonality", "Sales"
    ]

    # Check for missing fields
    missing_fields = [field for field in required_fields if field not in data]
    if missing_fields:
        return jsonify({"error": f"Missing required fields: {', '.join(missing_fields)}"}), 400

    # Basic type validation (can be more extensive)
    try:
        new_entry_data = {field: [data[field]] for field in required_fields}
        # Attempt to cast to expected types to catch obvious errors
        new_entry_data["Units Sold"] = [int(data["Units Sold"])]
        new_entry_data["Price"] = [float(data["Price"])]
        new_entry_data["Discount"] = [float(data["Discount"])]
        new_entry_data["Holiday/Promotion"] = [int(data["Holiday/Promotion"])]
        new_entry_data["Competitor Pricing"] = [float(data["Competitor Pricing"])]
        new_entry_data["Sales"] = [float(data["Sales"])]
    except (ValueError, TypeError) as e:
        return jsonify({"error": f"Invalid data type for one or more fields: {str(e)}"}), 400

    try:
        new_entry_df = pd.DataFrame(new_entry_data)
        
        # Append to CSV without header and index
        # The CSV already has an unnamed index column, so we don't want pandas to add another.
        # We also don't want to repeat headers.
        new_entry_df.to_csv(CSV_PATH, mode='a', header=False, index=False)
        
        app.logger.info(f"New entry added to {CSV_PATH} for Product ID {data.get('Product ID')}.")
        return jsonify({"message": "Entry added successfully to dataset.csv"}), 201
    except Exception as e:
        app.logger.error(f"Error adding entry to CSV: {str(e)}")
        return jsonify({"error": f"Failed to add entry to CSV: {str(e)}"}), 500



